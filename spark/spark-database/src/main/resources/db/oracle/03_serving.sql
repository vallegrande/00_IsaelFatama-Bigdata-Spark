-- Capa SERVING: lo que consume el dashboard. Se reemplaza por lote (BATCH_ID).
-- ROW_NO conserva el orden de las filas; LOADED_AT dice cuando se cargo el lote.
-- SERVING_RESUMEN guarda el resumen (JSON) de cada lote: el ultimo por JOB_TYPE es el lote vigente.
-- Cada tabla tiene su tabla _LOAD donde Spark deja el lote antes de moverlo.

CREATE TABLE SERVING_RENDIMIENTO (
    ESTUDIANTE_ID VARCHAR2(200),
    NOMBRES VARCHAR2(200),
    APELLIDOS VARCHAR2(200),
    SECCION VARCHAR2(200),
    SEMESTRE_ID VARCHAR2(200),
    PERIODO VARCHAR2(200),
    CURSO_ID VARCHAR2(200),
    CURSO VARCHAR2(200),
    DOCENTE VARCHAR2(200),
    CREDITOS NUMBER(10),
    EVALUACIONES NUMBER(19),
    EVALUACIONES_PENDIENTES NUMBER(19),
    PROMEDIO BINARY_DOUBLE,
    NOTA_FINAL NUMBER(10),
    SESIONES NUMBER(19),
    PRESENTES NUMBER(19),
    TARDANZAS NUMBER(19),
    FALTAS NUMBER(19),
    JUSTIFICADAS NUMBER(19),
    ASISTENCIA_PCT BINARY_DOUBLE,
    INASISTENCIA_PCT BINARY_DOUBLE,
    CONDICION VARCHAR2(200),
    REQUIERE_ATENCION NUMBER(1),
    ALERTAS VARCHAR2(4000),
    ROW_NO NUMBER(10) NOT NULL,
    BATCH_ID VARCHAR2(200) NOT NULL,
    LOADED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL
);

