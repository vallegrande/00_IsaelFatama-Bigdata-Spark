    CURSO_ID VARCHAR2(200),
    NOMBRE VARCHAR2(200),
    SEMESTRE_ID VARCHAR2(200),
    CREDITOS VARCHAR2(200),
    HORAS_SEMANALES VARCHAR2(200),
    DOCENTE VARCHAR2(200)
);

