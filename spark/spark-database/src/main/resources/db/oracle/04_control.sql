-- Capa CONTROL: filas rechazadas por la validacion, por lote.

CREATE TABLE ETL_RECHAZADOS (
    TABLA VARCHAR2(200),
    FILA NUMBER(10),
    CLAVE VARCHAR2(4000),
    MOTIVOS VARCHAR2(4000),
    REGISTRO VARCHAR2(4000),
    BATCH_ID VARCHAR2(200) NOT NULL
);

CREATE INDEX IX_ETL_RECHAZADOS_BATCH ON ETL_RECHAZADOS (BATCH_ID);

CREATE TABLE ETL_RECHAZADOS_LOAD (
    TABLA VARCHAR2(200),
    FILA NUMBER(10),
    CLAVE VARCHAR2(4000),
    MOTIVOS VARCHAR2(4000),
    REGISTRO VARCHAR2(4000),
    BATCH_ID VARCHAR2(200) NOT NULL
);

