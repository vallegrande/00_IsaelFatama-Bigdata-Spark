-- Capa CORE: datos limpios tipados, una fila por clave natural (se cargan con MERGE).
-- Cada tabla tiene su tabla _LOAD: donde Spark deja el lote antes del MERGE. Es permanente y se puede consultar.

CREATE TABLE CORE_SEMESTRES (
    SEMESTRE_ID VARCHAR2(200),
    NUMERO NUMBER(10),
    NOMBRE VARCHAR2(200),
    PERIODO VARCHAR2(200),
    FECHA_INICIO DATE,
    FECHA_FIN DATE,
    BATCH_ID VARCHAR2(200) NOT NULL,
    CONSTRAINT PK_CORE_SEMESTRES PRIMARY KEY (SEMESTRE_ID)
);

CREATE TABLE CORE_SEMESTRES_LOAD (
    SEMESTRE_ID VARCHAR2(200),
    NUMERO NUMBER(10),
    NOMBRE VARCHAR2(200),
    PERIODO VARCHAR2(200),
    FECHA_INICIO DATE,
    FECHA_FIN DATE,
    BATCH_ID VARCHAR2(200) NOT NULL
);

CREATE TABLE CORE_CURSOS (
    CURSO_ID VARCHAR2(200),
    NOMBRE VARCHAR2(200),
    SEMESTRE_ID VARCHAR2(200),
    CREDITOS NUMBER(10),
    HORAS_SEMANALES NUMBER(10),
    DOCENTE VARCHAR2(200),
    BATCH_ID VARCHAR2(200) NOT NULL,
    CONSTRAINT PK_CORE_CURSOS PRIMARY KEY (CURSO_ID)
);

CREATE TABLE CORE_CURSOS_LOAD (
    CURSO_ID VARCHAR2(200),
    NOMBRE VARCHAR2(200),
    SEMESTRE_ID VARCHAR2(200),
    CREDITOS NUMBER(10),
    HORAS_SEMANALES NUMBER(10),
    DOCENTE VARCHAR2(200),
    BATCH_ID VARCHAR2(200) NOT NULL
);

CREATE TABLE CORE_ESTUDIANTES (
    ESTUDIANTE_ID VARCHAR2(200),
    NOMBRES VARCHAR2(200),
    APELLIDOS VARCHAR2(200),
    CORREO VARCHAR2(200),
    SEMESTRE_ID VARCHAR2(200),
    SECCION VARCHAR2(200),
    BATCH_ID VARCHAR2(200) NOT NULL,
    CONSTRAINT PK_CORE_ESTUDIANTES PRIMARY KEY (ESTUDIANTE_ID)
);

CREATE TABLE CORE_ESTUDIANTES_LOAD (
    ESTUDIANTE_ID VARCHAR2(200),
    NOMBRES VARCHAR2(200),
    APELLIDOS VARCHAR2(200),
    CORREO VARCHAR2(200),
    SEMESTRE_ID VARCHAR2(200),
    SECCION VARCHAR2(200),
    BATCH_ID VARCHAR2(200) NOT NULL
);

CREATE TABLE CORE_NOTAS (
    ESTUDIANTE_ID VARCHAR2(200),
    CURSO_ID VARCHAR2(200),
    PERIODO VARCHAR2(200),
    EVALUACION VARCHAR2(200),
    PESO BINARY_DOUBLE,
    NOTA BINARY_DOUBLE,
    FECHA_REGISTRO DATE,
    BATCH_ID VARCHAR2(200) NOT NULL,
    CONSTRAINT PK_CORE_NOTAS PRIMARY KEY (ESTUDIANTE_ID, CURSO_ID, PERIODO, EVALUACION)
);

CREATE TABLE CORE_NOTAS_LOAD (
    ESTUDIANTE_ID VARCHAR2(200),
    CURSO_ID VARCHAR2(200),
    PERIODO VARCHAR2(200),
    EVALUACION VARCHAR2(200),
    PESO BINARY_DOUBLE,
    NOTA BINARY_DOUBLE,
    FECHA_REGISTRO DATE,
    BATCH_ID VARCHAR2(200) NOT NULL
);

CREATE TABLE CORE_ASISTENCIA (
    ESTUDIANTE_ID VARCHAR2(200),
    CURSO_ID VARCHAR2(200),
    PERIODO VARCHAR2(200),
    SEMANA NUMBER(10),
    FECHA DATE,
    ESTADO VARCHAR2(200),
    BATCH_ID VARCHAR2(200) NOT NULL,
    CONSTRAINT PK_CORE_ASISTENCIA PRIMARY KEY (ESTUDIANTE_ID, CURSO_ID, PERIODO, SEMANA)
);

CREATE TABLE CORE_ASISTENCIA_LOAD (
    ESTUDIANTE_ID VARCHAR2(200),
    CURSO_ID VARCHAR2(200),
    PERIODO VARCHAR2(200),
    SEMANA NUMBER(10),
    FECHA DATE,
    ESTADO VARCHAR2(200),
    BATCH_ID VARCHAR2(200) NOT NULL
);

